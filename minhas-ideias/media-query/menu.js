function mostrarConteudo(id) {
            // Esconde todos os conteúdos
            document.getElementById('nintendinho').style.display = 'none';
            document.getElementById('supernintendo').style.display = 'none';
            document.getElementById('nintendo64').style.display = 'none';
            document.getElementById('playstation').style.display = 'none';
            document.getElementById('playstation2').style.display = 'none';

            // Mostra o conteúdo selecionado
            document.getElementById(id).style.display = 'block';
        }
        


        


        
        